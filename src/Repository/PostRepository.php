    // Dans PostRepository.php
    public function findAllPostsAndReposts()
    {
        $qb = $this->createQueryBuilder('p')
            ->leftJoin('p.reposts', 'r')
            ->addSelect('r')
            ->orderBy('COALESCE(r.createdAt, p.createdAt)', 'DESC')
            ->getQuery();

        return $qb->getResult();
    }

